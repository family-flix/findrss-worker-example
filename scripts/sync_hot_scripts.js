import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

export function render_script_sources(entries) {
  const ordered = [...entries].sort(([left], [right]) => left < right ? -1 : left > right ? 1 : 0);
  const hot = ordered.filter(([path]) => path.startsWith("hot/"));
  const version = createHash("sha256").update(hot.map(([path, source]) => path.slice(4) + source).join("\n")).digest("hex").slice(0, 16);
  const index_of = path => ordered.findIndex(([name]) => name === path);
  for (const path of ["rss/apple.js", "clip/website.js"]) {
    if (index_of(path) < 0) throw new Error("脚本仓库缺少 " + path);
  }
  return "// Generated by scripts/sync_hot_scripts.js from https://github.com/ltaoo/findrss-scripts.\n"
    + "// Edit the independent scripts repository, then regenerate this build snapshot.\n"
    + ordered.map(([, source], index) => `const source_${index} = ${JSON.stringify(source)};`).join("\n")
    + `\n\nexport const HOT_SCRIPTS_VERSION = ${JSON.stringify(version)};\nexport const hot_scripts = [\n`
    + hot.map(([path]) => `  { id: ${JSON.stringify(path.slice(4, -3))}, source: source_${index_of(path)} },`).join("\n") + "\n];\n"
    + "\nexport const script_sources = Object.freeze({\n"
    + ordered.map(([path], index) => `  ${JSON.stringify(path)}: source_${index},`).join("\n") + "\n});\n"
    + `\nexport const apple_script = source_${index_of("rss/apple.js")};\nexport const clip_script_source = source_${index_of("clip/website.js")};\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const target = new URL("../server/infra/builtin_script_sources.js", import.meta.url);
  const directory = process.argv.slice(2).find(argument => argument !== "--check");
  if (directory) {
    const root = resolve(directory), entries = [];
    for (const folder of ["hot", "rss", "clip", "detect"]) {
      const base = resolve(root, folder);
      for (const name of readdirSync(base).filter(name => name.endsWith(".js")).sort()) {
        entries.push([folder ? folder + "/" + name : name, readFileSync(resolve(base, name), "utf8")]);
      }
    }
    const source = render_script_sources(entries);
    if (process.argv.includes("--check")) {
      if (!existsSync(target) || readFileSync(target, "utf8") !== source) throw new Error("内置脚本快照未同步，请先运行同步命令");
    } else if (!existsSync(target) || readFileSync(target, "utf8") !== source) writeFileSync(target, source);
  } else if (!existsSync(target)) {
    throw new Error("缺少内置脚本快照，请运行 node scripts/sync_hot_scripts.js <findrss-scripts 目录>");
  }
}
